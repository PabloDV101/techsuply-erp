-- Sales storage only: APIs, workflows, stock updates and commercial policies remain future work.
-- Historical migrations are left intact; usuario.cliente_id remains untouched pending data diagnosis.
CREATE SEQUENCE cotizacion_folio_seq;
CREATE SEQUENCE pedido_venta_folio_seq;
CREATE SEQUENCE despacho_folio_seq;

CREATE TABLE clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0),
    nombre_razon_social varchar(160) NOT NULL CHECK (length(btrim(nombre_razon_social)) > 0),
    identificador_fiscal varchar(20) UNIQUE,
    correo varchar(150), telefono varchar(30), direccion text,
    limite_credito numeric(14,2) NOT NULL DEFAULT 0 CHECK (limite_credito >= 0),
    plazo_credito_dias smallint NOT NULL DEFAULT 30 CHECK (plazo_credito_dias >= 0),
    activo boolean NOT NULL DEFAULT true
);
CREATE INDEX idx_clientes_activo_codigo ON clientes(activo, codigo);

CREATE TABLE cotizaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    cliente_id bigint NOT NULL REFERENCES clientes(id),
    vendedor_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    fecha timestamptz NOT NULL DEFAULT now(), vigencia_hasta date NOT NULL,
    estado varchar(15) NOT NULL CHECK (estado IN ('BORRADOR','VIGENTE','ACEPTADA','VENCIDA','CANCELADA')),
    subtotal numeric(14,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    impuestos numeric(14,2) NOT NULL DEFAULT 0 CHECK (impuestos >= 0),
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0)
);
CREATE INDEX idx_cotizaciones_cliente_fecha ON cotizaciones(cliente_id, fecha DESC);
CREATE INDEX idx_cotizaciones_estado_fecha ON cotizaciones(estado, fecha DESC);
CREATE TABLE detalles_cotizacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id bigint NOT NULL REFERENCES cotizaciones(id), producto_id bigint NOT NULL REFERENCES productos(id),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario >= 0),
    descuento_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (descuento_pct BETWEEN 0 AND 100),
    tasa_impuesto numeric(5,2) NOT NULL CHECK (tasa_impuesto BETWEEN 0 AND 100),
    UNIQUE(cotizacion_id, producto_id)
);
CREATE INDEX idx_detalles_cotizacion_producto ON detalles_cotizacion(producto_id);

CREATE TABLE pedidos_venta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    cliente_id bigint NOT NULL REFERENCES clientes(id), vendedor_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    cotizacion_id bigint NOT NULL UNIQUE REFERENCES cotizaciones(id), almacen_id bigint NOT NULL REFERENCES almacenes(id),
    creado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    canal varchar(15) NOT NULL CHECK (canal = 'INTERNO'),
    modalidad varchar(15) NOT NULL CHECK (modalidad = 'CONTADO'),
    fecha timestamptz NOT NULL DEFAULT now(),
    estado varchar(25) NOT NULL CHECK (estado IN ('BORRADOR','CONFIRMADO','PARCIALMENTE_DESPACHADO','DESPACHADO','CANCELADO')),
    subtotal numeric(14,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    impuestos numeric(14,2) NOT NULL DEFAULT 0 CHECK (impuestos >= 0),
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0),
    observaciones text
);
CREATE INDEX idx_pedidos_cliente_fecha ON pedidos_venta(cliente_id, fecha DESC);
CREATE INDEX idx_pedidos_estado_fecha ON pedidos_venta(estado, fecha DESC);
CREATE TABLE detalles_pedido (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id bigint NOT NULL REFERENCES pedidos_venta(id), producto_id bigint NOT NULL REFERENCES productos(id),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    cantidad_reservada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0),
    cantidad_despachada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_despachada >= 0),
    precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario >= 0),
    descuento_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (descuento_pct BETWEEN 0 AND 100),
    tasa_impuesto numeric(5,2) NOT NULL CHECK (tasa_impuesto BETWEEN 0 AND 100),
    CONSTRAINT ck_detalle_pedido_cantidades CHECK (cantidad_reservada + cantidad_despachada <= cantidad),
    UNIQUE(pedido_id, producto_id)
);
CREATE INDEX idx_detalles_pedido_producto ON detalles_pedido(producto_id);
CREATE TABLE despachos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    pedido_id bigint NOT NULL REFERENCES pedidos_venta(id), almacen_id bigint NOT NULL REFERENCES almacenes(id),
    registrado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id), fecha timestamptz NOT NULL DEFAULT now(),
    estado varchar(15) NOT NULL CHECK (estado IN ('BORRADOR','CONFIRMADO','CANCELADO')),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0)
);
CREATE INDEX idx_despachos_pedido ON despachos(pedido_id);
CREATE INDEX idx_despachos_estado_fecha ON despachos(estado, fecha DESC);
CREATE TABLE detalles_despacho (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    despacho_id bigint NOT NULL REFERENCES despachos(id), detalle_pedido_id bigint NOT NULL REFERENCES detalles_pedido(id),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario numeric(16,4) CHECK (costo_unitario >= 0),
    UNIQUE(despacho_id, detalle_pedido_id)
);
CREATE INDEX idx_detalles_despacho_pedido ON detalles_despacho(detalle_pedido_id);

ALTER TABLE movimientos_inventario ADD COLUMN detalle_despacho_id bigint UNIQUE REFERENCES detalles_despacho(id);
ALTER TABLE movimientos_inventario DROP CONSTRAINT ck_movimiento_fuente_tipo;
ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_movimiento_fuente_tipo CHECK (
    (tipo='ENTRADA' AND motivo='RECEPCION_COMPRA' AND detalle_recepcion_id IS NOT NULL AND detalle_ajuste_id IS NULL AND detalle_despacho_id IS NULL)
    OR (tipo IN ('ENTRADA','SALIDA') AND motivo='AJUSTE' AND detalle_recepcion_id IS NULL AND detalle_ajuste_id IS NOT NULL AND detalle_despacho_id IS NULL)
    OR (tipo='SALIDA' AND motivo='DESPACHO_VENTA' AND detalle_recepcion_id IS NULL AND detalle_ajuste_id IS NULL AND detalle_despacho_id IS NOT NULL)
);
CREATE OR REPLACE FUNCTION validar_fuente_movimiento_inventario() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NEW.motivo = 'RECEPCION_COMPRA' THEN
        PERFORM 1 FROM detalles_recepcion d JOIN recepciones_compra r ON r.id=d.recepcion_id
        JOIN detalles_orden_compra o ON o.id=d.detalle_orden_compra_id AND o.orden_compra_id=r.orden_compra_id
        WHERE d.id=NEW.detalle_recepcion_id AND o.producto_id=NEW.producto_id AND r.almacen_id=NEW.almacen_id
          AND d.cantidad_aceptada=NEW.cantidad AND d.precio_unitario_recibido=NEW.costo_unitario FOR SHARE OF d,r,o;
    ELSIF NEW.motivo = 'AJUSTE' THEN
        PERFORM 1 FROM detalles_ajuste_inventario d JOIN ajustes_inventario a ON a.id=d.ajuste_inventario_id
        WHERE d.id=NEW.detalle_ajuste_id AND d.producto_id=NEW.producto_id AND a.almacen_id=NEW.almacen_id AND d.cantidad=NEW.cantidad
          AND ((d.tipo='POSITIVO' AND NEW.tipo='ENTRADA' AND d.costo_unitario=NEW.costo_unitario)
            OR (d.tipo='NEGATIVO' AND NEW.tipo='SALIDA' AND (d.costo_unitario IS NULL OR d.costo_unitario=NEW.costo_unitario))) FOR SHARE OF d,a;
    ELSIF NEW.motivo = 'DESPACHO_VENTA' THEN
        PERFORM 1 FROM detalles_despacho d JOIN despachos s ON s.id=d.despacho_id
        JOIN detalles_pedido l ON l.id=d.detalle_pedido_id AND l.pedido_id=s.pedido_id
        JOIN pedidos_venta p ON p.id=s.pedido_id AND p.almacen_id=s.almacen_id
        WHERE d.id=NEW.detalle_despacho_id AND s.estado='BORRADOR' AND l.producto_id=NEW.producto_id AND s.almacen_id=NEW.almacen_id
          AND d.cantidad=NEW.cantidad AND d.costo_unitario=NEW.costo_unitario FOR SHARE OF d,s,l,p;
    ELSE
        RAISE EXCEPTION 'Fuente de inventario no admitida' USING ERRCODE='23514';
    END IF;
    IF NOT FOUND THEN RAISE EXCEPTION 'El movimiento no coincide con su fuente' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;

