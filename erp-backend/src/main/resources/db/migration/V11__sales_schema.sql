-- Protect source attributes once a movement exists, without freezing order progress.
CREATE FUNCTION proteger_fuente_despacho() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE parent_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'detalles_despacho' THEN
        IF TG_OP = 'INSERT' THEN parent_id := NEW.despacho_id; ELSE parent_id := OLD.despacho_id; END IF;
        PERFORM 1 FROM despachos WHERE id=parent_id FOR UPDATE;
        IF EXISTS (SELECT 1 FROM despachos WHERE id=parent_id AND estado='CONFIRMADO')
           OR (TG_OP <> 'INSERT' AND EXISTS (SELECT 1 FROM movimientos_inventario WHERE detalle_despacho_id=OLD.id)) THEN
            RAISE EXCEPTION 'El detalle de despacho es histórico' USING ERRCODE='23514';
        END IF;
        IF TG_OP = 'UPDATE' AND NEW.despacho_id <> OLD.despacho_id THEN
            PERFORM 1 FROM despachos WHERE id=NEW.despacho_id FOR UPDATE;
            IF EXISTS (SELECT 1 FROM despachos WHERE id=NEW.despacho_id AND estado='CONFIRMADO') THEN
                RAISE EXCEPTION 'El despacho está confirmado' USING ERRCODE='23514';
            END IF;
        END IF;
    ELSIF TG_TABLE_NAME = 'despachos' THEN
        IF OLD.estado='CONFIRMADO' THEN RAISE EXCEPTION 'El despacho está confirmado' USING ERRCODE='23514'; END IF;
        IF EXISTS (SELECT 1 FROM detalles_despacho d JOIN movimientos_inventario m ON m.detalle_despacho_id=d.id WHERE d.despacho_id=OLD.id)
           AND (TG_OP='DELETE' OR NEW.pedido_id<>OLD.pedido_id OR NEW.almacen_id<>OLD.almacen_id OR NEW.estado<>'CONFIRMADO') THEN
            RAISE EXCEPTION 'El despacho ya tiene movimientos' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME = 'detalles_pedido' THEN
        IF (TG_OP='DELETE' OR NEW.pedido_id<>OLD.pedido_id OR NEW.producto_id<>OLD.producto_id)
           AND EXISTS (SELECT 1 FROM detalles_despacho d JOIN movimientos_inventario m ON m.detalle_despacho_id=d.id WHERE d.detalle_pedido_id=OLD.id) THEN
            RAISE EXCEPTION 'La línea tiene movimientos de despacho' USING ERRCODE='23514';
        END IF;
    ELSE
        IF (TG_OP='DELETE' OR NEW.almacen_id<>OLD.almacen_id)
           AND EXISTS (SELECT 1 FROM despachos s JOIN detalles_despacho d ON d.despacho_id=s.id JOIN movimientos_inventario m ON m.detalle_despacho_id=d.id WHERE s.pedido_id=OLD.id) THEN
            RAISE EXCEPTION 'El pedido tiene movimientos de despacho' USING ERRCODE='23514';
        END IF;
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER proteger_detalle_despacho BEFORE INSERT OR UPDATE OR DELETE ON detalles_despacho FOR EACH ROW EXECUTE FUNCTION proteger_fuente_despacho();
CREATE TRIGGER proteger_despacho BEFORE UPDATE OR DELETE ON despachos FOR EACH ROW EXECUTE FUNCTION proteger_fuente_despacho();
CREATE TRIGGER proteger_detalle_pedido_despachado BEFORE UPDATE OR DELETE ON detalles_pedido FOR EACH ROW EXECUTE FUNCTION proteger_fuente_despacho();
CREATE TRIGGER proteger_pedido_despachado BEFORE UPDATE OR DELETE ON pedidos_venta FOR EACH ROW EXECUTE FUNCTION proteger_fuente_despacho();
