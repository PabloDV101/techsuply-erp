CREATE TABLE categorias_producto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    descripcion varchar(250),
    categoria_padre_id bigint REFERENCES categorias_producto(id),
    activa boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_categoria_no_autopadre CHECK (categoria_padre_id IS NULL OR categoria_padre_id <> id)
);

CREATE INDEX idx_categorias_producto_padre ON categorias_producto(categoria_padre_id);

