-- Sprint 1: master data needed by purchase orders and goods receipts.
-- Existing categories (V3), users and roles (V1/V2) are reused.
CREATE TABLE departamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_departamentos_codigo_canonico
        CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0),
    CONSTRAINT ck_departamentos_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE proveedores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre_razon_social varchar(160) NOT NULL,
    identificador_fiscal varchar(20) UNIQUE,
    contacto varchar(100),
    correo varchar(150),
    telefono varchar(30),
    direccion text,
    plazo_credito_dias smallint NOT NULL DEFAULT 0,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_proveedores_codigo_canonico
        CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0),
    CONSTRAINT ck_proveedores_nombre_no_vacio CHECK (length(btrim(nombre_razon_social)) > 0),
    CONSTRAINT ck_proveedores_plazo_no_negativo CHECK (plazo_credito_dias >= 0)
);

CREATE TABLE almacenes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(100) NOT NULL,
    sede varchar(120),
    ubicacion varchar(200),
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_almacenes_codigo_canonico
        CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0),
    CONSTRAINT ck_almacenes_nombre_no_vacio CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE productos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku varchar(30) NOT NULL UNIQUE,
    nombre varchar(160) NOT NULL,
    descripcion text,
    unidad_medida varchar(20) NOT NULL DEFAULT 'PIEZA',
    categoria_id bigint NOT NULL REFERENCES categorias_producto(id),
    proveedor_principal_id bigint REFERENCES proveedores(id),
    precio_lista numeric(14,2) NOT NULL DEFAULT 0,
    costo_referencia numeric(14,2) NOT NULL DEFAULT 0,
    tasa_impuesto numeric(5,2) NOT NULL DEFAULT 16,
    punto_reorden numeric(14,3) NOT NULL DEFAULT 0,
    cantidad_reorden numeric(14,3) NOT NULL DEFAULT 1,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_productos_sku_canonico
        CHECK (sku = upper(btrim(sku)) AND length(sku) > 0),
    CONSTRAINT ck_productos_nombre_no_vacio CHECK (length(btrim(nombre)) > 0),
    CONSTRAINT ck_productos_unidad_no_vacia CHECK (length(btrim(unidad_medida)) > 0),
    CONSTRAINT ck_productos_precio_no_negativo CHECK (precio_lista >= 0),
    CONSTRAINT ck_productos_costo_no_negativo CHECK (costo_referencia >= 0),
    CONSTRAINT ck_productos_tasa_valida CHECK (tasa_impuesto BETWEEN 0 AND 100),
    CONSTRAINT ck_productos_punto_reorden_no_negativo CHECK (punto_reorden >= 0),
    CONSTRAINT ck_productos_cantidad_reorden_no_negativa CHECK (cantidad_reorden >= 0)
);

CREATE INDEX idx_productos_categoria_activo ON productos(categoria_id, activo);
CREATE INDEX idx_productos_proveedor_principal ON productos(proveedor_principal_id);

