CREATE TABLE minimos_producto_almacen (
 producto_id bigint NOT NULL REFERENCES productos(id),
 almacen_id bigint NOT NULL REFERENCES almacenes(id),
 minimo numeric(14,3) NOT NULL CHECK (minimo >= 0),
 PRIMARY KEY(producto_id,almacen_id)
);
CREATE TABLE clasificaciones_margen_cuenta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuenta_contable_id bigint NOT NULL REFERENCES cuentas_contables(id),
 clasificacion varchar(24) NOT NULL CHECK (clasificacion IN ('INGRESO_OPERATIVO','COSTO_OPERATIVO','GASTO_OPERATIVO','NO_OPERATIVO')),
 fecha_inicio date NOT NULL CHECK (isfinite(fecha_inicio)),
 fecha_fin date NOT NULL CHECK (isfinite(fecha_fin) AND fecha_fin>=fecha_inicio),
 registrado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
 registrado_en timestamptz NOT NULL DEFAULT now(),
 anulada_en timestamptz,
 motivo_anulacion varchar(300),
 CHECK ((anulada_en IS NULL AND motivo_anulacion IS NULL) OR (anulada_en IS NOT NULL AND length(btrim(motivo_anulacion)) BETWEEN 1 AND 300)),
 EXCLUDE USING gist (cuenta_contable_id WITH =, daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE (anulada_en IS NULL)
);
CREATE FUNCTION proteger_clasificacion_margen() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND OLD.anulada_en IS NULL AND NEW.anulada_en IS NOT NULL
 AND (to_jsonb(NEW)-ARRAY['anulada_en','motivo_anulacion'])=(to_jsonb(OLD)-ARRAY['anulada_en','motivo_anulacion']) THEN RETURN NEW; END IF;
 IF TG_OP<>'INSERT' THEN RAISE EXCEPTION 'Clasificación histórica' USING ERRCODE='23514'; END IF;
 IF NEW.anulada_en IS NOT NULL OR NOT EXISTS (
  SELECT 1 FROM cuentas_contables c WHERE c.id=NEW.cuenta_contable_id AND c.acepta_movimientos AND c.tipo IN ('INGRESO','COSTO','GASTO')
  AND (NEW.clasificacion='NO_OPERATIVO' OR NEW.clasificacion=c.tipo||'_OPERATIVO')) THEN
  RAISE EXCEPTION 'Clasificación incompatible' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER clasificacion_margen_inmutable BEFORE INSERT OR UPDATE OR DELETE ON clasificaciones_margen_cuenta
 FOR EACH ROW EXECUTE FUNCTION proteger_clasificacion_margen();
