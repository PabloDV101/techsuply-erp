-- Supplier invoices are separate from accepted receipts. Validation clears GRNI and creates AP.
CREATE SEQUENCE factura_proveedor_folio_seq;

CREATE TABLE facturas_proveedor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_interno varchar(30) NOT NULL UNIQUE,
    proveedor_id bigint NOT NULL REFERENCES proveedores(id),
    orden_compra_id bigint NOT NULL UNIQUE REFERENCES ordenes_compra(id),
    numero_factura_proveedor varchar(60) NOT NULL,
    fecha_emision date NOT NULL CHECK (isfinite(fecha_emision)),
    fecha_vencimiento date NOT NULL CHECK (isfinite(fecha_vencimiento)),
    subtotal numeric NOT NULL CHECK (subtotal >= 0 AND subtotal <= 999999999999.99 AND scale(subtotal) <= 2),
    impuestos numeric NOT NULL CHECK (impuestos >= 0 AND impuestos <= 999999999999.99 AND scale(impuestos) <= 2),
    total numeric NOT NULL CHECK (total > 0 AND total <= 999999999999.99 AND scale(total) <= 2),
    estado varchar(15) NOT NULL DEFAULT 'REGISTRADA' CHECK (estado IN ('REGISTRADA','VALIDADA')),
    registrada_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    validada_por_usuario_id bigint REFERENCES usuarios(id),
    registrada_en timestamptz NOT NULL DEFAULT now(),
    validada_en timestamptz,
    asiento_contable_id bigint UNIQUE REFERENCES asientos_contables(id),
    UNIQUE (proveedor_id, numero_factura_proveedor),
    CHECK (fecha_vencimiento >= fecha_emision),
    CHECK (total = subtotal + impuestos),
    CHECK ((estado='REGISTRADA' AND validada_por_usuario_id IS NULL AND validada_en IS NULL AND asiento_contable_id IS NULL)
        OR (estado='VALIDADA' AND validada_por_usuario_id IS NOT NULL AND validada_en IS NOT NULL AND asiento_contable_id IS NOT NULL))
);
CREATE INDEX idx_facturas_proveedor_estado ON facturas_proveedor(estado,id);

CREATE TABLE detalles_factura_proveedor (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_proveedor_id bigint NOT NULL REFERENCES facturas_proveedor(id),
    detalle_orden_compra_id bigint NOT NULL REFERENCES detalles_orden_compra(id),
    cantidad_facturada numeric NOT NULL CHECK (cantidad_facturada > 0 AND cantidad_facturada <= 99999999999.999 AND scale(cantidad_facturada) <= 3),
    precio_unitario numeric NOT NULL CHECK (precio_unitario >= 0 AND precio_unitario <= 999999999999.99 AND scale(precio_unitario) <= 2),
    descuento_pct numeric NOT NULL CHECK (descuento_pct BETWEEN 0 AND 100 AND scale(descuento_pct) <= 2),
    tasa_impuesto numeric NOT NULL CHECK (tasa_impuesto BETWEEN 0 AND 100 AND scale(tasa_impuesto) <= 2),
    subtotal numeric NOT NULL CHECK (subtotal >= 0 AND subtotal <= 999999999999.99 AND scale(subtotal) <= 2),
    impuestos numeric NOT NULL CHECK (impuestos >= 0 AND impuestos <= 999999999999.99 AND scale(impuestos) <= 2),
    total numeric NOT NULL CHECK (total >= 0 AND total <= 999999999999.99 AND scale(total) <= 2),
    UNIQUE (factura_proveedor_id, detalle_orden_compra_id),
    CHECK (total = subtotal + impuestos)
);

CREATE TABLE configuracion_cuentas_factura_proveedor (
    concepto varchar(30) PRIMARY KEY CHECK (concepto IN ('IVA_ACREDITABLE','CUENTAS_POR_PAGAR')),
    cuenta_contable_id bigint NOT NULL REFERENCES cuentas_contables(id),
    actualizado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cuentas_por_pagar (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_proveedor_id bigint NOT NULL UNIQUE REFERENCES facturas_proveedor(id),
    proveedor_id bigint NOT NULL REFERENCES proveedores(id),
    asiento_contable_id bigint NOT NULL UNIQUE REFERENCES asientos_contables(id),
    monto_original numeric NOT NULL CHECK (monto_original > 0 AND monto_original <= 999999999999.99 AND scale(monto_original) <= 2),
    fecha_emision date NOT NULL CHECK (isfinite(fecha_emision)),
    fecha_vencimiento date NOT NULL CHECK (isfinite(fecha_vencimiento)),
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (fecha_vencimiento >= fecha_emision)
);
CREATE INDEX idx_cuentas_por_pagar_proveedor_vencimiento ON cuentas_por_pagar(proveedor_id,fecha_vencimiento,id);

