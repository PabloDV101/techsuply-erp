-- Initial security schema for EMPTY databases only. Never baseline an existing schema automatically.
CREATE TABLE usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(60) NOT NULL UNIQUE,
    correo varchar(150) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    empleado_id bigint UNIQUE,
    cliente_id bigint UNIQUE,
    activo boolean NOT NULL DEFAULT true,
    intentos_fallidos smallint NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta timestamptz,
    ultimo_acceso timestamptz,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (empleado_id IS NULL OR cliente_id IS NULL),
    CHECK (username = lower(btrim(username)) AND length(username) > 0),
    CHECK (correo = lower(btrim(correo)) AND length(correo) > 0)
);
-- Shared namespace prevents username/email ambiguity, including concurrent inserts.
CREATE TABLE identificadores_usuario (
    identificador varchar(150) PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE
);
CREATE FUNCTION sincronizar_identificadores_usuario() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM identificadores_usuario WHERE usuario_id = NEW.id;
    INSERT INTO identificadores_usuario(identificador, usuario_id)
        SELECT DISTINCT identificador, NEW.id FROM (VALUES (NEW.username), (NEW.correo)) AS v(identificador);
    RETURN NEW;
END;
$$;
CREATE TRIGGER usuarios_identificadores AFTER INSERT OR UPDATE OF username, correo ON usuarios
    FOR EACH ROW EXECUTE FUNCTION sincronizar_identificadores_usuario();

CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(30) NOT NULL UNIQUE,
    nombre varchar(80) NOT NULL,
    descripcion varchar(250),
    activo boolean NOT NULL DEFAULT true,
    CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0)
);
CREATE TABLE permisos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(60) NOT NULL UNIQUE,
    modulo varchar(40) NOT NULL,
    accion varchar(30) NOT NULL,
    descripcion varchar(250),
    UNIQUE(modulo, accion),
    CHECK (codigo = upper(btrim(codigo)) AND length(codigo) > 0),
    CHECK (modulo = upper(btrim(modulo)) AND length(modulo) > 0),
    CHECK (accion = upper(btrim(accion)) AND length(accion) > 0)
);
CREATE TABLE usuarios_roles (
    usuario_id bigint NOT NULL REFERENCES usuarios(id),
    rol_id bigint NOT NULL REFERENCES roles(id),
    asignado_por_usuario_id bigint REFERENCES usuarios(id),
    asignado_en timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(usuario_id, rol_id)
);
CREATE INDEX usuarios_roles_rol_idx ON usuarios_roles(rol_id);
CREATE TABLE roles_permisos (
    rol_id bigint NOT NULL REFERENCES roles(id),
    permiso_id bigint NOT NULL REFERENCES permisos(id),
    PRIMARY KEY(rol_id, permiso_id)
);
CREATE INDEX roles_permisos_permiso_idx ON roles_permisos(permiso_id);
CREATE TABLE tokens_sesion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuarios(id),
    token_hash varchar(255) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    emitido_en timestamptz NOT NULL,
    vence_en timestamptz NOT NULL,
    revocado_en timestamptz,
    CHECK (vence_en > emitido_en)
);
CREATE INDEX tokens_sesion_usuario_activo_idx ON tokens_sesion(usuario_id) WHERE revocado_en IS NULL;
