-- Internal inbox only. External transports and durable outbox are separate, future decisions.
CREATE TABLE notificaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL REFERENCES usuarios(id),
    tipo_evento varchar(40) NOT NULL,
    modulo varchar(40) NOT NULL,
    entidad varchar(80) NOT NULL,
    entidad_id bigint NOT NULL,
    clave_operacion varchar(120) NOT NULL,
    canal varchar(15) NOT NULL DEFAULT 'APP' CHECK (canal = 'APP'),
    asunto varchar(200) NOT NULL,
    cuerpo text NOT NULL,
    estado varchar(15) NOT NULL DEFAULT 'NO_LEIDA' CHECK (estado IN ('NO_LEIDA', 'LEIDA')),
    creada_en timestamptz NOT NULL DEFAULT now(),
    leida_en timestamptz,
    CONSTRAINT uq_notificacion_operacion_destinatario UNIQUE (tipo_evento, clave_operacion, usuario_id),
    CONSTRAINT ck_notificacion_lectura CHECK ((estado = 'LEIDA') = (leida_en IS NOT NULL))
);
CREATE INDEX idx_notificaciones_usuario_fecha ON notificaciones(usuario_id, creada_en DESC, id DESC);
CREATE INDEX idx_notificaciones_usuario_estado_fecha ON notificaciones(usuario_id, estado, creada_en DESC, id DESC);
