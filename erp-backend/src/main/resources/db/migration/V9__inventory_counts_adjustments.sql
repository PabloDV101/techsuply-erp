-- Inventory documents and adjustment movement sources. Existing reception entries are preserved.
CREATE SEQUENCE conteo_inventario_folio_seq;
CREATE SEQUENCE ajuste_inventario_folio_seq;

CREATE TABLE conteos_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    almacen_id bigint NOT NULL REFERENCES almacenes(id),
    creado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    fecha_programada date NOT NULL,
    estado varchar(15) NOT NULL CHECK (estado IN ('PROGRAMADO','EN_CAPTURA','CERRADO','CANCELADO')),
    clase varchar(10) NOT NULL CHECK (clase IN ('CICLICO','GENERAL'))
);
CREATE INDEX idx_conteos_almacen_estado_fecha ON conteos_inventario(almacen_id, estado, fecha_programada DESC);

CREATE TABLE detalles_conteo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conteo_id bigint NOT NULL REFERENCES conteos_inventario(id),
    producto_id bigint NOT NULL REFERENCES productos(id),
    cantidad_sistema numeric(14,3) NOT NULL CHECK (cantidad_sistema >= 0),
    cantidad_contada numeric(14,3) NOT NULL CHECK (cantidad_contada >= 0),
    diferencia numeric(14,3) NOT NULL,
    existencia_previa boolean NOT NULL,
    version_existencia int,
    CONSTRAINT ck_conteo_diferencia CHECK (diferencia = cantidad_contada - cantidad_sistema),
    CONSTRAINT ck_conteo_existencia_version CHECK ((existencia_previa AND version_existencia IS NOT NULL AND version_existencia >= 0) OR (NOT existencia_previa AND version_existencia IS NULL AND cantidad_sistema = 0)),
    UNIQUE (conteo_id, producto_id)
);
CREATE INDEX idx_detalles_conteo_producto ON detalles_conteo(producto_id);

CREATE TABLE ajustes_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    almacen_id bigint NOT NULL REFERENCES almacenes(id),
    motivo text NOT NULL CHECK (length(btrim(motivo)) > 0),
    solicitado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    autorizado_por_usuario_id bigint REFERENCES usuarios(id),
    clave_idempotencia varchar(120) NOT NULL UNIQUE CHECK (length(btrim(clave_idempotencia)) > 0),
    estado varchar(15) NOT NULL CHECK (estado IN ('PENDIENTE','APROBADO','APLICADO','RECHAZADO')),
    fecha timestamptz NOT NULL DEFAULT now(),
    autorizado_en timestamptz,
    motivo_rechazo text,
    aplicado_en timestamptz,
    CONSTRAINT ck_ajuste_segregacion CHECK (autorizado_por_usuario_id IS NULL OR autorizado_por_usuario_id <> solicitado_por_usuario_id),
    CONSTRAINT ck_ajuste_estado_actor CHECK (
        (estado = 'PENDIENTE' AND autorizado_por_usuario_id IS NULL AND autorizado_en IS NULL AND motivo_rechazo IS NULL AND aplicado_en IS NULL)
        OR (estado = 'APROBADO' AND autorizado_por_usuario_id IS NOT NULL AND autorizado_en IS NOT NULL AND motivo_rechazo IS NULL AND aplicado_en IS NULL)
        OR (estado = 'APLICADO' AND autorizado_por_usuario_id IS NOT NULL AND autorizado_en IS NOT NULL AND motivo_rechazo IS NULL AND aplicado_en IS NOT NULL)
        OR (estado = 'RECHAZADO' AND autorizado_por_usuario_id IS NOT NULL AND autorizado_en IS NOT NULL AND motivo_rechazo IS NOT NULL AND length(btrim(motivo_rechazo)) > 0 AND aplicado_en IS NULL)
    )
);
CREATE INDEX idx_ajustes_almacen_estado_fecha ON ajustes_inventario(almacen_id, estado, fecha DESC);

CREATE TABLE detalles_ajuste_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ajuste_inventario_id bigint NOT NULL REFERENCES ajustes_inventario(id),
    producto_id bigint NOT NULL REFERENCES productos(id),
    tipo varchar(12) NOT NULL CHECK (tipo IN ('POSITIVO','NEGATIVO')),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario numeric(16,4) CHECK (costo_unitario >= 0),
    motivo_linea varchar(250),
    detalle_conteo_id bigint REFERENCES detalles_conteo(id),
    CONSTRAINT ck_ajuste_positivo_costo CHECK (tipo <> 'POSITIVO' OR costo_unitario IS NOT NULL),
    UNIQUE (ajuste_inventario_id, producto_id)
);
CREATE INDEX idx_detalles_ajuste_conteo ON detalles_ajuste_inventario(detalle_conteo_id);
CREATE INDEX idx_detalles_ajuste_producto ON detalles_ajuste_inventario(producto_id);

ALTER TABLE movimientos_inventario DROP CONSTRAINT movimientos_inventario_tipo_check;
ALTER TABLE movimientos_inventario DROP CONSTRAINT movimientos_inventario_motivo_check;
ALTER TABLE movimientos_inventario ALTER COLUMN detalle_recepcion_id DROP NOT NULL;
ALTER TABLE movimientos_inventario ADD COLUMN detalle_ajuste_id bigint UNIQUE REFERENCES detalles_ajuste_inventario(id);
ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_movimiento_fuente_tipo CHECK (
    (tipo = 'ENTRADA' AND motivo = 'RECEPCION_COMPRA' AND detalle_recepcion_id IS NOT NULL AND detalle_ajuste_id IS NULL)
    OR (tipo IN ('ENTRADA','SALIDA') AND motivo = 'AJUSTE' AND detalle_recepcion_id IS NULL AND detalle_ajuste_id IS NOT NULL)
);

