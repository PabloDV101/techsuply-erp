-- Customer receivables are a detail of the already-posted sales invoice balance.
-- Payments/applications are introduced separately; never persist a duplicate mutable balance.

CREATE TABLE cuentas_por_cobrar (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_venta_id bigint NOT NULL UNIQUE REFERENCES facturas_venta(id),
    cliente_id bigint NOT NULL REFERENCES clientes(id),
    monto_original numeric NOT NULL CHECK (
        monto_original > 0 AND monto_original <= 999999999999.99 AND scale(monto_original) <= 2
    ),
    fecha_emision date NOT NULL CHECK (isfinite(fecha_emision)),
    fecha_vencimiento date NOT NULL CHECK (isfinite(fecha_vencimiento)),
    creado_en timestamptz NOT NULL DEFAULT now(),
    CHECK (fecha_vencimiento >= fecha_emision)
);
CREATE INDEX idx_cuentas_por_cobrar_cliente_vencimiento
    ON cuentas_por_cobrar(cliente_id, fecha_vencimiento, id);

CREATE FUNCTION validar_cuenta_por_cobrar_venta() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'El origen y el importe de una cuenta por cobrar son históricos' USING ERRCODE='23514';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM facturas_venta f
        JOIN integracion_factura_venta_contabilidad i ON i.factura_venta_id=f.id
        JOIN asientos_contables a ON a.id=i.asiento_contable_id
        WHERE f.id=NEW.factura_venta_id AND f.estado='EMITIDA'
          AND f.cliente_id=NEW.cliente_id AND f.total=NEW.monto_original
          AND f.fecha_emision=NEW.fecha_emision AND f.fecha_vencimiento=NEW.fecha_vencimiento
          AND i.estado='CONTABILIZADA' AND a.estado='CONTABILIZADO'
          AND a.origen_modulo='VENTAS' AND a.origen_tipo='FACTURA_VENTA' AND a.origen_id=f.id
    ) THEN
        RAISE EXCEPTION 'La cuenta requiere una factura emitida y contabilizada' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER cuenta_por_cobrar_venta_historica
    BEFORE INSERT OR UPDATE OR DELETE ON cuentas_por_cobrar
    FOR EACH ROW EXECUTE FUNCTION validar_cuenta_por_cobrar_venta();

