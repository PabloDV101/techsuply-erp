-- Internal commercial document only: no CFDI, payment, receivable or accounting entry.
CREATE SEQUENCE factura_venta_folio_seq;

CREATE TABLE facturas_venta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (length(btrim(folio)) > 0),
    pedido_id bigint NOT NULL UNIQUE REFERENCES pedidos_venta(id),
    cliente_id bigint NOT NULL REFERENCES clientes(id),
    emitida_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    fecha_emision date NOT NULL,
    fecha_vencimiento date NOT NULL,
    subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0),
    impuestos numeric(14,2) NOT NULL CHECK (impuestos >= 0),
    total numeric(14,2) NOT NULL CHECK (total >= 0 AND total = subtotal + impuestos),
    estado varchar(20) NOT NULL CHECK (estado IN ('BORRADOR','EMITIDA')),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0),
    CHECK (fecha_vencimiento = fecha_emision)
);
CREATE INDEX idx_facturas_venta_cliente_fecha ON facturas_venta(cliente_id, fecha_emision DESC, id DESC);

CREATE TABLE detalles_factura_venta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_venta_id bigint NOT NULL REFERENCES facturas_venta(id),
    detalle_pedido_id bigint NOT NULL REFERENCES detalles_pedido(id),
    producto_id bigint NOT NULL REFERENCES productos(id),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario >= 0),
    descuento_pct numeric(5,2) NOT NULL CHECK (descuento_pct BETWEEN 0 AND 100),
    tasa_impuesto numeric(5,2) NOT NULL CHECK (tasa_impuesto BETWEEN 0 AND 100),
    subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0),
    impuestos numeric(14,2) NOT NULL CHECK (impuestos >= 0),
    total numeric(14,2) NOT NULL CHECK (total = subtotal + impuestos),
    UNIQUE(factura_venta_id, detalle_pedido_id),
    CHECK (subtotal = round(cantidad * precio_unitario * (1 - descuento_pct / 100), 2)),
    CHECK (impuestos = round(cantidad * precio_unitario * (1 - descuento_pct / 100) * tasa_impuesto / 100, 2))
);
CREATE INDEX idx_detalles_factura_venta_pedido ON detalles_factura_venta(detalle_pedido_id);

CREATE FUNCTION validar_factura_venta() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE p pedidos_venta%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado = 'EMITIDA' THEN RAISE EXCEPTION 'La factura emitida es histórica' USING ERRCODE='23514'; END IF;
        RETURN OLD;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.estado = 'EMITIDA' THEN
        RAISE EXCEPTION 'La factura emitida es histórica' USING ERRCODE='23514';
    END IF;
    IF TG_OP = 'UPDATE' AND (NEW.folio IS DISTINCT FROM OLD.folio OR NEW.pedido_id IS DISTINCT FROM OLD.pedido_id
        OR NEW.cliente_id IS DISTINCT FROM OLD.cliente_id OR NEW.emitida_por_usuario_id IS DISTINCT FROM OLD.emitida_por_usuario_id
        OR NEW.fecha_emision IS DISTINCT FROM OLD.fecha_emision OR NEW.fecha_vencimiento IS DISTINCT FROM OLD.fecha_vencimiento
        OR NEW.subtotal IS DISTINCT FROM OLD.subtotal OR NEW.impuestos IS DISTINCT FROM OLD.impuestos
        OR NEW.total IS DISTINCT FROM OLD.total OR NEW.clave_idempotencia IS DISTINCT FROM OLD.clave_idempotencia) THEN
        RAISE EXCEPTION 'Las condiciones de la factura no se pueden cambiar' USING ERRCODE='23514';
    END IF;
    IF TG_OP = 'INSERT' AND NEW.estado <> 'BORRADOR' THEN
        RAISE EXCEPTION 'La factura debe prepararse antes de emitir' USING ERRCODE='23514';
    END IF;
    SELECT * INTO p FROM pedidos_venta WHERE id=NEW.pedido_id FOR UPDATE;
    IF NOT FOUND OR p.estado <> 'DESPACHADO' OR p.cliente_id <> NEW.cliente_id OR p.subtotal <> NEW.subtotal
        OR p.impuestos <> NEW.impuestos OR p.total <> NEW.total THEN
        RAISE EXCEPTION 'Factura incompatible con el pedido' USING ERRCODE='23514';
    END IF;
    IF EXISTS (SELECT 1 FROM detalles_pedido l WHERE l.pedido_id=NEW.pedido_id AND (
          l.cantidad_despachada <> l.cantidad OR l.cantidad_reservada <> 0 OR
          coalesce((SELECT sum(d.cantidad) FROM detalles_despacho d JOIN despachos s ON s.id=d.despacho_id
             JOIN movimientos_inventario m ON m.detalle_despacho_id=d.id
             WHERE d.detalle_pedido_id=l.id AND s.pedido_id=NEW.pedido_id AND s.estado='CONFIRMADO'),0) <> l.cantidad)) THEN
        RAISE EXCEPTION 'El pedido no tiene salidas confirmadas completas' USING ERRCODE='23514';
    END IF;
    IF NEW.estado = 'EMITIDA' THEN
        IF NOT EXISTS (SELECT 1 FROM detalles_factura_venta WHERE factura_venta_id=NEW.id)
           OR EXISTS (SELECT 1 FROM detalles_pedido l WHERE l.pedido_id=NEW.pedido_id
                AND (l.cantidad_despachada <> l.cantidad OR l.cantidad_reservada <> 0
                     OR NOT EXISTS (SELECT 1 FROM detalles_factura_venta f WHERE f.factura_venta_id=NEW.id AND f.detalle_pedido_id=l.id)))
           OR (SELECT coalesce(sum(subtotal),0) FROM detalles_factura_venta WHERE factura_venta_id=NEW.id) <> NEW.subtotal
           OR (SELECT coalesce(sum(impuestos),0) FROM detalles_factura_venta WHERE factura_venta_id=NEW.id) <> NEW.impuestos THEN
            RAISE EXCEPTION 'Factura incompleta o importes incompatibles' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER validar_cabecera_factura BEFORE INSERT OR UPDATE OR DELETE ON facturas_venta FOR EACH ROW EXECUTE FUNCTION validar_factura_venta();

CREATE FUNCTION validar_detalle_factura_venta() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'El detalle de factura es histórico' USING ERRCODE='23514'; END IF;
    PERFORM 1 FROM facturas_venta f JOIN detalles_pedido l ON l.pedido_id=f.pedido_id
    WHERE f.id=NEW.factura_venta_id AND f.estado='BORRADOR' AND l.id=NEW.detalle_pedido_id
      AND l.producto_id=NEW.producto_id AND l.cantidad=NEW.cantidad AND l.precio_unitario=NEW.precio_unitario
      AND l.descuento_pct=NEW.descuento_pct AND l.tasa_impuesto=NEW.tasa_impuesto
    FOR UPDATE OF f FOR SHARE OF l;
    IF NOT FOUND THEN RAISE EXCEPTION 'Detalle incompatible con pedido' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER validar_linea_factura BEFORE INSERT OR UPDATE OR DELETE ON detalles_factura_venta FOR EACH ROW EXECUTE FUNCTION validar_detalle_factura_venta();

CREATE FUNCTION exigir_factura_emitida_al_commit() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM facturas_venta WHERE id=NEW.id AND estado='BORRADOR') THEN
        RAISE EXCEPTION 'La factura debe emitirse en la misma transacción' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER factura_emitida_al_commit AFTER INSERT OR UPDATE ON facturas_venta DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION exigir_factura_emitida_al_commit();

