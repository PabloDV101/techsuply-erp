CREATE TABLE eventos_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint REFERENCES usuarios(id),
    actor_tipo varchar(10) NOT NULL CHECK (actor_tipo IN ('USUARIO', 'SISTEMA', 'ANONIMO')),
    modulo varchar(40) NOT NULL,
    entidad varchar(80) NOT NULL,
    entidad_id bigint,
    accion varchar(40) NOT NULL,
    resultado varchar(10) NOT NULL CHECK (resultado IN ('EXITO', 'DENEGADO')),
    motivo_codigo varchar(40),
    fecha timestamptz NOT NULL DEFAULT now(),
    detalle jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(detalle) = 'object'),
    CONSTRAINT ck_auditoria_actor CHECK (
        (actor_tipo = 'USUARIO' AND usuario_id IS NOT NULL)
        OR (actor_tipo IN ('SISTEMA', 'ANONIMO') AND usuario_id IS NULL)
    )
);
CREATE INDEX idx_auditoria_fecha ON eventos_auditoria(fecha DESC, id DESC);
CREATE INDEX idx_auditoria_actor_fecha ON eventos_auditoria(usuario_id, fecha DESC);
CREATE INDEX idx_auditoria_recurso_fecha ON eventos_auditoria(modulo, entidad, entidad_id, fecha DESC);

-- Business/API users must not rewrite history. A future retention process needs a reviewed migration.
CREATE FUNCTION impedir_mutacion_auditoria() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Los eventos de auditoría son inmutables';
END;
$$;
CREATE TRIGGER auditoria_solo_insercion BEFORE UPDATE OR DELETE ON eventos_auditoria
    FOR EACH ROW EXECUTE FUNCTION impedir_mutacion_auditoria();

