-- V14 remains immutable. V15 enables only audited, manually controlled posting,
-- reversal and draft lifecycle operations; no operational source integration is enabled.

ALTER TABLE asientos_contables
    ALTER COLUMN estado TYPE varchar(16),
    ADD COLUMN ultimo_motivo_edicion varchar(300),
    ADD COLUMN editado_por_usuario_id bigint REFERENCES usuarios(id),
    ADD COLUMN editado_en timestamptz,
    ADD COLUMN motivo_cancelacion varchar(300),
    ADD COLUMN cancelado_por_usuario_id bigint REFERENCES usuarios(id),
    ADD COLUMN cancelado_en timestamptz,
    ADD COLUMN motivo_reversion varchar(300);

DO $$
DECLARE constraint_name text;
BEGIN
    FOR constraint_name IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'asientos_contables'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) LIKE '%estado%'
    LOOP
        EXECUTE format('ALTER TABLE asientos_contables DROP CONSTRAINT %I', constraint_name);
    END LOOP;
END;
$$;

ALTER TABLE asientos_contables
    ADD CONSTRAINT ck_asiento_estado CHECK (estado IN ('BORRADOR','CONTABILIZADO','REVERSADO','CANCELADO')),
    ADD CONSTRAINT ck_asiento_estado_metadatos CHECK (
      (estado = 'BORRADOR' AND contabilizado_por_usuario_id IS NULL AND contabilizado_en IS NULL
        AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL AND motivo_cancelacion IS NULL)
      OR (estado IN ('CONTABILIZADO','REVERSADO') AND contabilizado_por_usuario_id IS NOT NULL AND contabilizado_en IS NOT NULL
        AND cancelado_por_usuario_id IS NULL AND cancelado_en IS NULL AND motivo_cancelacion IS NULL)
      OR (estado = 'CANCELADO' AND contabilizado_por_usuario_id IS NULL AND contabilizado_en IS NULL
        AND cancelado_por_usuario_id IS NOT NULL AND cancelado_en IS NOT NULL
        AND motivo_cancelacion IS NOT NULL AND length(btrim(motivo_cancelacion)) BETWEEN 1 AND 300)
    ),
    ADD CONSTRAINT ck_asiento_edicion_metadatos CHECK (
      (ultimo_motivo_edicion IS NULL AND editado_por_usuario_id IS NULL AND editado_en IS NULL)
      OR (ultimo_motivo_edicion IS NOT NULL AND length(btrim(ultimo_motivo_edicion)) BETWEEN 1 AND 300
        AND editado_por_usuario_id IS NOT NULL AND editado_en IS NOT NULL)
    ),
    ADD CONSTRAINT ck_asiento_motivo_reversion CHECK (
      (estado = 'REVERSADO' AND contraasiento_de_id IS NULL AND motivo_reversion IS NOT NULL
        AND length(btrim(motivo_reversion)) BETWEEN 1 AND 300)
      OR (estado = 'CONTABILIZADO' AND (
        (contraasiento_de_id IS NULL AND motivo_reversion IS NULL)
        OR (contraasiento_de_id IS NOT NULL AND motivo_reversion IS NOT NULL
          AND length(btrim(motivo_reversion)) BETWEEN 1 AND 300)))
      OR (estado IN ('BORRADOR','CANCELADO') AND contraasiento_de_id IS NULL AND motivo_reversion IS NULL)
    );

CREATE TABLE historial_asientos_contables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiento_id bigint NOT NULL REFERENCES asientos_contables(id),
    resultado_asiento_id bigint REFERENCES asientos_contables(id),
    actor_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    accion varchar(32) NOT NULL CHECK (accion IN ('BORRADOR_EDITADO','BORRADOR_CANCELADO','CONTABILIZADO','REVERSADO')),
    clave_idempotencia varchar(120) UNIQUE CHECK (clave_idempotencia IS NULL OR (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0)),
    huella_solicitud char(64),
    motivo varchar(300) CHECK (motivo IS NULL OR length(btrim(motivo)) BETWEEN 1 AND 300),
    registrado_en timestamptz NOT NULL,
    CHECK ((clave_idempotencia IS NULL AND huella_solicitud IS NULL)
        OR (clave_idempotencia IS NOT NULL AND huella_solicitud IS NOT NULL)),
    CHECK (accion NOT IN ('BORRADOR_EDITADO','BORRADOR_CANCELADO','REVERSADO') OR motivo IS NOT NULL)
);
CREATE INDEX idx_historial_asientos_asiento_fecha ON historial_asientos_contables(asiento_id, registrado_en, id);

