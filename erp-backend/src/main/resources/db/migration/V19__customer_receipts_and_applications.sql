-- Customer receipts are explicit operational evidence. Confirmation, applications and
-- their accounting entries commit atomically; unapplied funds remain customer advances.
CREATE SEQUENCE cobro_cliente_folio_seq;

CREATE TABLE configuracion_cuentas_cobro (
    medio varchar(20) PRIMARY KEY CHECK (medio IN ('EFECTIVO','TRANSFERENCIA','CHEQUE','TARJETA','OTRO')),
    cuenta_fondos_id bigint NOT NULL REFERENCES cuentas_contables(id),
    cuenta_anticipos_id bigint NOT NULL REFERENCES cuentas_contables(id),
    actualizado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    actualizado_en timestamptz NOT NULL,
    CHECK (cuenta_fondos_id <> cuenta_anticipos_id)
);

CREATE TABLE cobros_clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE,
    cliente_id bigint NOT NULL REFERENCES clientes(id),
    fecha timestamptz NOT NULL,
    monto numeric NOT NULL CHECK (monto > 0 AND monto <= 999999999999.99 AND scale(monto) <= 2),
    medio varchar(20) NOT NULL CHECK (medio IN ('EFECTIVO','TRANSFERENCIA','CHEQUE','TARJETA','OTRO')),
    referencia varchar(100) CHECK (referencia IS NULL OR length(btrim(referencia)) BETWEEN 1 AND 100),
    registrado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia=btrim(clave_idempotencia) AND length(btrim(clave_idempotencia)) BETWEEN 1 AND 100),
    estado varchar(15) NOT NULL CHECK (estado IN ('REGISTRADO','CONFIRMADO')),
    asiento_contable_id bigint UNIQUE REFERENCES asientos_contables(id),
    fecha_contable date,
    confirmado_por_usuario_id bigint REFERENCES usuarios(id),
    confirmado_en timestamptz,
    CHECK ((estado='REGISTRADO' AND asiento_contable_id IS NULL AND fecha_contable IS NULL AND confirmado_por_usuario_id IS NULL AND confirmado_en IS NULL)
        OR (estado='CONFIRMADO' AND asiento_contable_id IS NOT NULL AND fecha_contable IS NOT NULL AND confirmado_por_usuario_id IS NOT NULL AND confirmado_en IS NOT NULL))
);
CREATE INDEX idx_cobros_cliente_fecha ON cobros_clientes(cliente_id,fecha DESC,id DESC);

CREATE TABLE aplicaciones_cobro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cobro_id bigint NOT NULL REFERENCES cobros_clientes(id),
    cuenta_por_cobrar_id bigint NOT NULL REFERENCES cuentas_por_cobrar(id),
    monto_aplicado numeric NOT NULL CHECK (monto_aplicado > 0 AND monto_aplicado <= 999999999999.99 AND scale(monto_aplicado) <= 2),
    fecha_aplicacion timestamptz NOT NULL DEFAULT now(),
    aplicado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    clave_idempotencia varchar(100) NOT NULL UNIQUE CHECK (clave_idempotencia=btrim(clave_idempotencia) AND length(btrim(clave_idempotencia)) BETWEEN 1 AND 100),
    huella_solicitud char(64) NOT NULL CHECK (huella_solicitud ~ '^[0-9a-f]{64}$'),
    asiento_contable_id bigint UNIQUE REFERENCES asientos_contables(id)
);
CREATE INDEX idx_aplicaciones_cxc ON aplicaciones_cobro(cuenta_por_cobrar_id,id);
CREATE INDEX idx_aplicaciones_cobro ON aplicaciones_cobro(cobro_id,id);

CREATE FUNCTION validar_aplicacion_cobro() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE receipt cobros_clientes%ROWTYPE;
DECLARE receivable_client bigint;
DECLARE receivable_original numeric;
DECLARE receipt_applied numeric;
DECLARE receivable_applied numeric;
BEGIN
  IF TG_OP='UPDATE' AND OLD.asiento_contable_id IS NULL AND NEW.asiento_contable_id IS NOT NULL
     AND NEW.id=OLD.id AND NEW.cobro_id=OLD.cobro_id AND NEW.cuenta_por_cobrar_id=OLD.cuenta_por_cobrar_id
     AND NEW.monto_aplicado=OLD.monto_aplicado AND NEW.fecha_aplicacion=OLD.fecha_aplicacion
     AND NEW.aplicado_por_usuario_id=OLD.aplicado_por_usuario_id AND NEW.clave_idempotencia=OLD.clave_idempotencia
     AND EXISTS (SELECT 1 FROM asientos_contables WHERE id=NEW.asiento_contable_id AND estado='CONTABILIZADO'
                 AND origen_modulo='CONTABILIDAD' AND origen_tipo='APLICACION_COBRO' AND origen_id=NEW.id) THEN RETURN NEW; END IF;
  IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'Las aplicaciones contabilizadas son históricas' USING ERRCODE='23514'; END IF;
  SELECT * INTO receipt FROM cobros_clientes WHERE id=NEW.cobro_id FOR UPDATE;
  SELECT cliente_id,monto_original INTO receivable_client,receivable_original
    FROM cuentas_por_cobrar WHERE id=NEW.cuenta_por_cobrar_id FOR UPDATE;
  IF receipt.estado <> 'CONFIRMADO' OR receipt.cliente_id IS DISTINCT FROM receivable_client THEN
    RAISE EXCEPTION 'La aplicación requiere cobro confirmado y el mismo cliente' USING ERRCODE='23514';
  END IF;
  IF NEW.asiento_contable_id IS NOT NULL THEN RAISE EXCEPTION 'La aplicación debe persistirse antes de su asiento' USING ERRCODE='23514'; END IF;
  SELECT coalesce(sum(monto_aplicado),0) INTO receipt_applied FROM aplicaciones_cobro WHERE cobro_id=NEW.cobro_id;
  SELECT coalesce(sum(monto_aplicado),0) INTO receivable_applied FROM aplicaciones_cobro WHERE cuenta_por_cobrar_id=NEW.cuenta_por_cobrar_id;
  IF receipt_applied+NEW.monto_aplicado > receipt.monto OR receivable_applied+NEW.monto_aplicado > receivable_original THEN
    RAISE EXCEPTION 'La aplicación supera el disponible del cobro o saldo de la cuenta' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER aplicacion_cobro_historica BEFORE INSERT OR UPDATE OR DELETE ON aplicaciones_cobro
FOR EACH ROW EXECUTE FUNCTION validar_aplicacion_cobro();

CREATE FUNCTION exigir_asiento_aplicacion_cobro() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE entry_id bigint;
BEGIN
  SELECT asiento_contable_id INTO entry_id FROM aplicaciones_cobro WHERE id=NEW.id;
  IF entry_id IS NULL OR NOT EXISTS (
      SELECT 1 FROM asientos_contables a WHERE a.id=entry_id AND a.estado='CONTABILIZADO'
        AND a.origen_modulo='CONTABILIDAD' AND a.origen_tipo='APLICACION_COBRO' AND a.origen_id=NEW.id
  ) THEN
    RAISE EXCEPTION 'La aplicación debe terminar la transacción con su asiento contabilizado' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER aplicacion_cobro_asiento_requerido
AFTER INSERT OR UPDATE ON aplicaciones_cobro
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION exigir_asiento_aplicacion_cobro();

CREATE FUNCTION proteger_cobro_cliente() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Los cobros no se eliminan' USING ERRCODE='23514'; END IF;
  IF TG_OP='INSERT' THEN
    IF NEW.estado <> 'REGISTRADO' OR NEW.asiento_contable_id IS NOT NULL THEN RAISE EXCEPTION 'El cobro inicia registrado' USING ERRCODE='23514'; END IF;
    RETURN NEW;
  END IF;
  IF OLD.estado='REGISTRADO' AND NEW.estado='CONFIRMADO'
     AND NEW.id=OLD.id AND NEW.folio=OLD.folio AND NEW.cliente_id=OLD.cliente_id AND NEW.fecha=OLD.fecha
     AND NEW.monto=OLD.monto AND NEW.medio=OLD.medio AND NEW.referencia IS NOT DISTINCT FROM OLD.referencia
     AND NEW.registrado_por_usuario_id=OLD.registrado_por_usuario_id AND NEW.clave_idempotencia=OLD.clave_idempotencia
     AND NEW.asiento_contable_id IS NOT NULL AND NEW.fecha_contable IS NOT NULL
     AND NEW.confirmado_por_usuario_id IS NOT NULL AND NEW.confirmado_en IS NOT NULL
     AND EXISTS (SELECT 1 FROM asientos_contables a WHERE a.id=NEW.asiento_contable_id AND a.estado='CONTABILIZADO'
        AND a.origen_modulo='CONTABILIDAD' AND a.origen_tipo='COBRO_CLIENTE' AND a.origen_id=NEW.id) THEN RETURN NEW; END IF;
  RAISE EXCEPTION 'El cobro confirmado es inmutable' USING ERRCODE='23514';
END;
$$;
CREATE TRIGGER cobro_cliente_historico BEFORE INSERT OR UPDATE OR DELETE ON cobros_clientes
FOR EACH ROW EXECUTE FUNCTION proteger_cobro_cliente();

