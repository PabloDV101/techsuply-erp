-- Initial purchase and inventory schema. Future document sources are added by later migrations.
CREATE SEQUENCE orden_compra_folio_seq;
CREATE SEQUENCE recepcion_compra_folio_seq;

CREATE TABLE ordenes_compra (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE,
    proveedor_id bigint NOT NULL REFERENCES proveedores(id),
    departamento_id bigint NOT NULL REFERENCES departamentos(id),
    creada_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    aprobada_por_usuario_id bigint REFERENCES usuarios(id),
    aprobada_en timestamptz,
    motivo_rechazo text,
    fecha timestamptz NOT NULL DEFAULT now(),
    estado varchar(25) NOT NULL CHECK (estado IN ('BORRADOR','PENDIENTE_APROBACION','APROBADA','ENVIADA','PARCIALMENTE_RECIBIDA','RECIBIDA','CANCELADA')),
    subtotal numeric(14,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    impuestos numeric(14,2) NOT NULL DEFAULT 0 CHECK (impuestos >= 0),
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    observaciones text
);
CREATE INDEX idx_ordenes_proveedor ON ordenes_compra(proveedor_id);
CREATE INDEX idx_ordenes_estado_fecha ON ordenes_compra(estado, fecha DESC);
CREATE INDEX idx_ordenes_fecha ON ordenes_compra(fecha DESC);

CREATE TABLE detalles_orden_compra (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_compra_id bigint NOT NULL REFERENCES ordenes_compra(id),
    producto_id bigint NOT NULL REFERENCES productos(id),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario numeric(14,2) NOT NULL CHECK (precio_unitario >= 0),
    descuento_pct numeric(5,2) NOT NULL DEFAULT 0 CHECK (descuento_pct BETWEEN 0 AND 100),
    tasa_impuesto numeric(5,2) NOT NULL CHECK (tasa_impuesto BETWEEN 0 AND 100),
    UNIQUE (orden_compra_id, producto_id)
);
CREATE INDEX idx_detalles_orden_producto ON detalles_orden_compra(producto_id);

CREATE TABLE recepciones_compra (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE,
    orden_compra_id bigint NOT NULL REFERENCES ordenes_compra(id),
    almacen_id bigint NOT NULL REFERENCES almacenes(id),
    registrada_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    clave_idempotencia varchar(120) NOT NULL UNIQUE CHECK (length(btrim(clave_idempotencia)) > 0),
    fecha timestamptz NOT NULL DEFAULT now(),
    estado varchar(20) NOT NULL CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA')),
    referencia_externa varchar(80),
    confirmada_en timestamptz
);
CREATE INDEX idx_recepciones_orden ON recepciones_compra(orden_compra_id);
CREATE INDEX idx_recepciones_estado_fecha ON recepciones_compra(estado, fecha DESC);
CREATE INDEX idx_recepciones_fecha ON recepciones_compra(fecha DESC);

CREATE TABLE detalles_recepcion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recepcion_id bigint NOT NULL REFERENCES recepciones_compra(id),
    detalle_orden_compra_id bigint NOT NULL REFERENCES detalles_orden_compra(id),
    cantidad_recibida numeric(14,3) NOT NULL CHECK (cantidad_recibida > 0),
    cantidad_aceptada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_aceptada >= 0),
    cantidad_rechazada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_rechazada >= 0),
    precio_unitario_recibido numeric(14,2) NOT NULL CHECK (precio_unitario_recibido >= 0),
    motivo_rechazo text,
    CONSTRAINT ck_recepcion_cantidades CHECK (cantidad_aceptada + cantidad_rechazada <= cantidad_recibida),
    UNIQUE (recepcion_id, detalle_orden_compra_id)
);
CREATE INDEX idx_detalles_recepcion_orden ON detalles_recepcion(detalle_orden_compra_id);

CREATE TABLE existencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint NOT NULL REFERENCES productos(id),
    almacen_id bigint NOT NULL REFERENCES almacenes(id),
    cantidad_fisica numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_fisica >= 0),
    cantidad_reservada numeric(14,3) NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0),
    costo_promedio numeric(14,4) NOT NULL DEFAULT 0 CHECK (costo_promedio >= 0),
    version int NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT ck_existencias_reservadas CHECK (cantidad_reservada <= cantidad_fisica),
    UNIQUE (producto_id, almacen_id)
);

CREATE TABLE movimientos_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint NOT NULL REFERENCES productos(id),
    almacen_id bigint NOT NULL REFERENCES almacenes(id),
    tipo varchar(12) NOT NULL CHECK (tipo = 'ENTRADA'),
    motivo varchar(35) NOT NULL CHECK (motivo = 'RECEPCION_COMPRA'),
    cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario numeric(14,4) NOT NULL DEFAULT 0 CHECK (costo_unitario >= 0),
    fecha timestamptz NOT NULL DEFAULT now(),
    usuario_id bigint NOT NULL REFERENCES usuarios(id),
    detalle_recepcion_id bigint NOT NULL UNIQUE REFERENCES detalles_recepcion(id),
    clave_operacion varchar(120) NOT NULL UNIQUE CHECK (length(btrim(clave_operacion)) > 0),
    referencia text
);
CREATE INDEX idx_movimientos_producto_almacen_fecha ON movimientos_inventario(producto_id, almacen_id, fecha DESC);

