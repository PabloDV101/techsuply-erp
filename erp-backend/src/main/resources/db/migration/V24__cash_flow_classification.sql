-- Cash-flow classifications are explicit, versioned by non-overlapping date ranges.
-- No default categorization is assigned to existing accounts or movements.
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE TABLE clasificaciones_flujo_cuenta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_contable_id bigint NOT NULL REFERENCES cuentas_contables(id),
    clasificacion varchar(24) NOT NULL CHECK (clasificacion IN ('EFECTIVO','CAPITAL_TRABAJO','INVERSION','FINANCIACION','NO_MONETARIO','RESULTADO')),
    fecha_inicio date NOT NULL CHECK (isfinite(fecha_inicio)),
    fecha_fin date NOT NULL CHECK (isfinite(fecha_fin) AND fecha_fin >= fecha_inicio),
    registrado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    registrado_en timestamptz NOT NULL DEFAULT now(),
    anulada_en timestamptz,
    anulada_por_usuario_id bigint REFERENCES usuarios(id),
    motivo_anulacion varchar(300),
    CHECK ((anulada_en IS NULL AND anulada_por_usuario_id IS NULL AND motivo_anulacion IS NULL) OR (anulada_en IS NOT NULL AND anulada_por_usuario_id IS NOT NULL AND motivo_anulacion IS NOT NULL AND length(btrim(motivo_anulacion)) BETWEEN 1 AND 300)),
    EXCLUDE USING gist (cuenta_contable_id WITH =, daterange(fecha_inicio,fecha_fin,'[]') WITH &&) WHERE (anulada_en IS NULL)
);
CREATE INDEX idx_flujo_cuenta_vigencia ON clasificaciones_flujo_cuenta(cuenta_contable_id,fecha_inicio,fecha_fin);

-- A non-cash balance change may represent several activities. Record its
-- reviewed classification per posted journal line, rather than inferring it.
CREATE TABLE clasificaciones_flujo_partida (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida_asiento_id bigint NOT NULL REFERENCES partidas_asiento(id),
    clasificacion varchar(24) NOT NULL CHECK (clasificacion IN ('OPERACION','INVERSION','FINANCIACION','NO_MONETARIO')),
    registrado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    registrado_en timestamptz NOT NULL DEFAULT now(),
    anulada_en timestamptz,
    anulada_por_usuario_id bigint REFERENCES usuarios(id),
    motivo_anulacion varchar(300),
    CHECK ((anulada_en IS NULL AND anulada_por_usuario_id IS NULL AND motivo_anulacion IS NULL) OR (anulada_en IS NOT NULL AND anulada_por_usuario_id IS NOT NULL AND motivo_anulacion IS NOT NULL AND length(btrim(motivo_anulacion)) BETWEEN 1 AND 300))
);
CREATE UNIQUE INDEX uq_flujo_partida_activa ON clasificaciones_flujo_partida(partida_asiento_id) WHERE anulada_en IS NULL;
INSERT INTO permisos(codigo,modulo,accion,descripcion) VALUES
 ('CONTABILIDAD_FLUJO_CLASIFICAR','CONTABILIDAD','FLUJO_CLASIFICAR','Clasificar cuentas y partidas para flujo de efectivo');
INSERT INTO roles_permisos(rol_id,permiso_id)
SELECT r.id,p.id FROM roles r CROSS JOIN permisos p WHERE r.codigo='ADMINISTRADOR' AND p.codigo='CONTABILIDAD_FLUJO_CLASIFICAR';

CREATE FUNCTION proteger_clasificacion_flujo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.anulada_en IS NULL AND NEW.anulada_en IS NOT NULL
       AND (to_jsonb(NEW) - ARRAY['anulada_en','anulada_por_usuario_id','motivo_anulacion']) = (to_jsonb(OLD) - ARRAY['anulada_en','anulada_por_usuario_id','motivo_anulacion']) THEN
        RETURN NEW;
    END IF;
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Las clasificaciones de flujo son históricas' USING ERRCODE='23514';
    END IF;
    IF NEW.anulada_en IS NOT NULL OR NEW.anulada_por_usuario_id IS NOT NULL OR NEW.motivo_anulacion IS NOT NULL THEN
        RAISE EXCEPTION 'Una clasificación nueva debe iniciar activa' USING ERRCODE='23514';
    END IF;
    IF TG_TABLE_NAME='clasificaciones_flujo_cuenta' THEN
      IF NOT EXISTS (
        SELECT 1 FROM cuentas_contables c WHERE c.id=NEW.cuenta_contable_id AND c.acepta_movimientos
          AND (NEW.clasificacion<>'EFECTIVO' OR (c.tipo='ACTIVO' AND c.naturaleza='DEUDORA'))
      ) THEN
        RAISE EXCEPTION 'Cuenta incompatible para clasificación de flujo' USING ERRCODE='23514';
      END IF;
    ELSIF TG_TABLE_NAME='clasificaciones_flujo_partida' THEN
      IF NOT EXISTS (
        SELECT 1 FROM partidas_asiento p JOIN asientos_contables a ON a.id=p.asiento_id
        WHERE p.id=NEW.partida_asiento_id AND a.estado IN ('CONTABILIZADO','REVERSADO')
      ) THEN
        RAISE EXCEPTION 'La clasificación requiere una partida contabilizada' USING ERRCODE='23514';
      END IF;
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER clasificacion_flujo_cuenta_historica BEFORE INSERT OR UPDATE OR DELETE ON clasificaciones_flujo_cuenta
    FOR EACH ROW EXECUTE FUNCTION proteger_clasificacion_flujo();
CREATE TRIGGER clasificacion_flujo_partida_historica BEFORE INSERT OR UPDATE OR DELETE ON clasificaciones_flujo_partida
    FOR EACH ROW EXECUTE FUNCTION proteger_clasificacion_flujo();
