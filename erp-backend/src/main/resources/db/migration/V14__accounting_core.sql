CREATE TABLE asientos_contables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio varchar(30) NOT NULL UNIQUE CHECK (folio = btrim(folio) AND length(folio) > 0),
    periodo_id bigint NOT NULL REFERENCES periodos_contables(id),
    fecha_contable date NOT NULL CHECK (isfinite(fecha_contable)),
    descripcion varchar(300) NOT NULL CHECK (length(btrim(descripcion)) > 0),
    origen_modulo varchar(30) NOT NULL CHECK (length(btrim(origen_modulo)) > 0),
    origen_tipo varchar(40) NOT NULL CHECK (length(btrim(origen_tipo)) > 0),
    origen_id bigint CHECK (origen_id > 0),
    clave_idempotencia varchar(120) NOT NULL UNIQUE CHECK (clave_idempotencia = btrim(clave_idempotencia) AND length(clave_idempotencia) > 0),
    contraasiento_de_id bigint UNIQUE REFERENCES asientos_contables(id),
    creado_por_usuario_id bigint NOT NULL REFERENCES usuarios(id),
    contabilizado_por_usuario_id bigint REFERENCES usuarios(id),
    estado varchar(12) NOT NULL CHECK (estado IN ('BORRADOR','CONTABILIZADO','REVERSADO')),
    contabilizado_en timestamptz,
    CHECK (contraasiento_de_id IS NULL OR contraasiento_de_id <> id),
    CHECK ((estado = 'BORRADOR' AND contabilizado_por_usuario_id IS NULL AND contabilizado_en IS NULL)
        OR (estado IN ('CONTABILIZADO','REVERSADO') AND contabilizado_por_usuario_id IS NOT NULL AND contabilizado_en IS NOT NULL))
);
CREATE INDEX idx_asientos_periodo_fecha ON asientos_contables(periodo_id, fecha_contable, id);
-- Prevent duplicate original entries, while allowing a future linked counter-entry.
CREATE UNIQUE INDEX uq_asiento_origen_original ON asientos_contables(origen_modulo, origen_tipo, origen_id)
    WHERE origen_id IS NOT NULL AND contraasiento_de_id IS NULL;

CREATE TABLE partidas_asiento (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiento_id bigint NOT NULL REFERENCES asientos_contables(id),
    numero_linea smallint NOT NULL CHECK (numero_linea > 0),
    cuenta_contable_id bigint NOT NULL REFERENCES cuentas_contables(id),
    -- Unconstrained numeric plus CHECK: numeric(14,2) alone would round excess precision before validation.
    debe numeric NOT NULL DEFAULT 0 CHECK (debe >= 0 AND debe <= 999999999999.99 AND scale(debe) <= 2),
    haber numeric NOT NULL DEFAULT 0 CHECK (haber >= 0 AND haber <= 999999999999.99 AND scale(haber) <= 2),
    descripcion varchar(200),
    UNIQUE (asiento_id, numero_linea),
    CHECK ((debe > 0 AND haber = 0) OR (haber > 0 AND debe = 0))
);
CREATE INDEX idx_partidas_cuenta_asiento ON partidas_asiento(cuenta_contable_id, asiento_id);

-- No posted history exists yet. Do not permit unsafe posting or synthetic operational sources
-- before the posting/reversal flow and source validation are implemented in a later migration.
CREATE FUNCTION limitar_asiento_a_borrador_manual() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado <> 'BORRADOR' OR NEW.origen_modulo <> 'MANUAL' OR NEW.origen_tipo <> 'MANUAL'
       OR NEW.origen_id IS NOT NULL OR NEW.contraasiento_de_id IS NOT NULL THEN
        RAISE EXCEPTION 'Solo se admite estructura de borrador manual; contabilización e integración aún no disponibles' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER asiento_solo_borrador_manual BEFORE INSERT OR UPDATE ON asientos_contables
FOR EACH ROW EXECUTE FUNCTION limitar_asiento_a_borrador_manual();
