-- Structural accounting foundation only. No posting, reversal, account mapping or integration is enabled.
CREATE SEQUENCE asiento_contable_folio_seq;

CREATE TABLE cuentas_contables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(30) NOT NULL UNIQUE CHECK (codigo = btrim(codigo) AND length(codigo) > 0),
    nombre varchar(150) NOT NULL CHECK (length(btrim(nombre)) > 0),
    tipo varchar(15) NOT NULL CHECK (tipo IN ('ACTIVO','PASIVO','CAPITAL','INGRESO','COSTO','GASTO')),
    naturaleza varchar(12) NOT NULL CHECK (naturaleza IN ('DEUDORA','ACREEDORA')),
    nivel smallint NOT NULL DEFAULT 1 CHECK (nivel > 0),
    cuenta_padre_id bigint REFERENCES cuentas_contables(id),
    acepta_movimientos boolean NOT NULL DEFAULT true,
    activa boolean NOT NULL DEFAULT true,
    CHECK (cuenta_padre_id IS NULL OR cuenta_padre_id <> id)
);
CREATE INDEX idx_cuentas_contables_padre ON cuentas_contables(cuenta_padre_id);

-- Built-in GiST daterange operator, no btree_gist extension or privileged installation required.
-- Both endpoints are inclusive; adjacent periods may not share a date.
CREATE TABLE periodos_contables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    estado varchar(10) NOT NULL CHECK (estado IN ('ABIERTO','CERRADO')),
    cerrado_por_usuario_id bigint REFERENCES usuarios(id),
    cerrado_en timestamptz,
    CHECK (isfinite(fecha_inicio) AND isfinite(fecha_fin) AND fecha_inicio <= fecha_fin),
    CHECK ((estado = 'ABIERTO' AND cerrado_por_usuario_id IS NULL AND cerrado_en IS NULL)
        OR (estado = 'CERRADO' AND cerrado_por_usuario_id IS NOT NULL AND cerrado_en IS NOT NULL)),
    EXCLUDE USING gist (daterange(fecha_inicio, fecha_fin, '[]') WITH &&)
);

CREATE FUNCTION proteger_periodo_cerrado_contable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.estado = 'CERRADO' THEN
        RAISE EXCEPTION 'El periodo cerrado es histórico y no puede reabrirse' USING ERRCODE='23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER periodo_cerrado_inmutable BEFORE UPDATE OR DELETE ON periodos_contables
FOR EACH ROW EXECUTE FUNCTION proteger_periodo_cerrado_contable();

